#!/usr/bin/env node
// GG Motion font library: list the bundled OFL fonts, or install chosen
// families into a video project so renders never depend on the network.
//
// Usage:
//   node fonts.mjs list
//   node fonts.mjs add <project-dir> <Family> [<Family> ...]
//
// `add` copies each family's woff2 files and OFL.txt into
// <project>/assets/fonts/<family>/, rewrites <project>/assets/fonts/fonts.css,
// and returns `head`: a <style> block with an @font-face for every bundled
// family installed there, using project-relative paths. Paste `head` into the
// composition <head>. `hf check` only sees @font-face written in the page, so a
// linked fonts.css renders but is reported as missing fonts.
// Prints one JSON line: {"ok":true,...} or {"ok":false,"error":...}.
import { copyFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const LIBRARY = join(dirname(fileURLToPath(import.meta.url)), "..", "fonts");

function done(result, code = 0) {
  process.stdout.write(`${JSON.stringify(result)}\n`);
  process.exit(code);
}
const fail = (error) => done({ ok: false, error }, 1);

/** @returns {Promise<Array<{family:string,dir:string,license:string,use?:string,files:Array<{file:string,style:string,weight:string,stretch:string|null}>}>>} */
async function manifest() {
  return JSON.parse(await readFile(join(LIBRARY, "fonts.json"), "utf8"));
}

/** `base` is the font folder as seen from the file that holds the rule. */
function fontFace(entry, file, base = "") {
  const lines = [
    `  font-family: "${entry.family}";`,
    `  src: url("${base}${entry.dir}/${file.file}") format("woff2");`,
    `  font-style: ${file.style};`,
    `  font-weight: ${file.weight};`,
  ];
  if (file.stretch) lines.push(`  font-stretch: ${file.stretch};`);
  lines.push("  font-display: block;");
  return `@font-face {\n${lines.join("\n")}\n}`;
}

const [command, ...rest] = process.argv.slice(2);
const fonts = await manifest().catch(() => fail(`Font library missing at ${LIBRARY}`));

if (command === "list") {
  done({
    ok: true,
    specimen: join(LIBRARY, "specimen.jpg"),
    families: fonts.map((f) => ({
      family: f.family,
      styles: f.files.map((file) => file.style),
      weight: f.files[0]?.weight,
      width: f.files[0]?.stretch ?? null,
      ...(f.use ? { use: f.use } : {}),
    })),
  });
}

if (command !== "add" || rest.length < 2) {
  fail("usage: fonts.mjs list | fonts.mjs add <project-dir> <Family> [<Family> ...]");
}

const [projectArg, ...names] = rest;
const project = resolve(projectArg);
const projectInfo = await stat(project).catch(() => undefined);
if (!projectInfo?.isDirectory()) fail(`Project folder not found: ${project}`);

const byName = new Map(fonts.map((f) => [f.family.toLowerCase(), f]));
const chosen = [];
for (const name of names) {
  const entry = byName.get(name.toLowerCase());
  if (!entry) {
    fail(`Unknown family "${name}". Bundled: ${fonts.map((f) => f.family).join(", ")}`);
  }
  chosen.push(entry);
}

const target = join(project, "assets", "fonts");
for (const entry of chosen) {
  const dir = join(target, entry.dir);
  await mkdir(dir, { recursive: true });
  for (const file of [...entry.files.map((f) => f.file), "OFL.txt"]) {
    await copyFile(join(LIBRARY, entry.dir, file), join(dir, file));
  }
}

// Rebuild the stylesheet from everything installed, so repeated `add` calls
// accumulate families instead of dropping earlier ones.
const installed = [];
for (const entry of fonts) {
  const present = await stat(join(target, entry.dir, entry.files[0]?.file ?? "")).catch(
    () => undefined,
  );
  if (present) installed.push(entry);
}
const rules = (base) =>
  installed.flatMap((entry) => entry.files.map((file) => fontFace(entry, file, base)));
const header =
  "/* Generated by GG Motion fonts.mjs. SIL OFL 1.1: licenses sit beside each family. */";
await writeFile(join(target, "fonts.css"), `${[header, ...rules("")].join("\n\n")}\n`);

done({
  ok: true,
  installed: installed.map((f) => f.family),
  head: `<style>\n${[header, ...rules("assets/fonts/")].join("\n")}\n</style>`,
  use: "Paste head into the composition <head>, replacing any earlier fonts block.",
});
