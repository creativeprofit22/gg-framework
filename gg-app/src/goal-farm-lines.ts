/**
 * A line for `kind`, chosen with `roll` (0 to 1), never `last` (the one this
 * critter said before) when there's another to pick.
 */
export function pickWorkLine(
  coordinator: boolean,
  kind: WorkKind,
  roll: number,
  last: string | null,
): string {
  const lines = (coordinator ? KEN_LINES : WORKER_LINES)[kind];
  const pool = lines.length > 1 && last ? lines.filter((line) => line !== last) : lines;
  return pool[Math.min(pool.length - 1, Math.floor(roll * pool.length))] ?? lines[0] ?? "";
}
